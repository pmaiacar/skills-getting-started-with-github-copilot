class TestIntegrationScenarios:
    """Integration tests for complete user flows"""
    
    def test_complete_signup_and_unregister_flow(self, client):
        """Test a complete flow of signing up and then unregistering"""
        email = "integration@mergington.edu"
        activity = "Art Studio"
        
        # Check initial state
        response = client.get("/activities")
        initial_participants = response.json()[activity]["participants"]
        assert email not in initial_participants
        
        # Sign up
        signup_response = client.post(f"/activities/{activity}/signup?email={email}")
        assert signup_response.status_code == 200
        
        # Verify signup
        response = client.get("/activities")
        after_signup_participants = response.json()[activity]["participants"]
        assert email in after_signup_participants
        
        # Unregister
        unregister_response = client.delete(f"/activities/{activity}/unregister?email={email}")
        assert unregister_response.status_code == 200
        
        # Verify unregistration
        response = client.get("/activities")
        final_participants = response.json()[activity]["participants"]
        assert email not in final_participants
    
    def test_multiple_students_signup_same_activity(self, client):
        """Test multiple students signing up for the same activity"""
        activity = "Drama Club"
        emails = [
            "student1@mergington.edu",
            "student2@mergington.edu",
            "student3@mergington.edu"
        ]
        
        for email in emails:
            response = client.post(f"/activities/{activity}/signup?email={email}")
            assert response.status_code == 200
        
        # Verify all students were added
        response = client.get("/activities")
        participants = response.json()[activity]["participants"]
        for email in emails:
            assert email in participants
